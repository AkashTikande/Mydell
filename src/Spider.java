public class Spider {
    public static void main(String[] args) {
        for (int i = 0; i <= 10; i++) {
            for (int j = 0; j<= i; j++) {                        // FOR I =0 AND J =0 OUTPUT BE LIKE 10 11, 20 21 22,
                System.out.println(i + " " + j);                // 30 31 32 33, 40 41 42 42 43 44. UPTO 10 10
                System.out.println("java programming");   // O/P = 1; 1 to 10 UPTO. 10; 1 to 10.  //
            }
        }
    }
}
