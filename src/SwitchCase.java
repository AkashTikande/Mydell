public class SwitchCase
{
    public static void main(String[] args) {
        int number = 20;
        switch(number)
        {
            case 10:
                System.out.println("10");
            case 20:
                System.out.println("20");
            case 30:
                System.out.println("30");
            case 40:
                System.out.println("40");
            default:
                System.out.println("Nighter satisfy in above conditions");
        }
    }
}
